#!/usr/bin/env python3
"""Keep js/version.js and sw.js VERSION in sync and regenerate sw-assets.js.
Usage: tools/bump.py [patch|minor|major|X.Y.Z]   (default patch). Run on every change before committing."""
import re, sys, os, json
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = lambda *a: os.path.join(R, *a)
cur = re.search(r"'(\d+)\.(\d+)\.(\d+)'", open(p('js/version.js')).read()).groups()
a = sys.argv[1] if len(sys.argv) > 1 else 'patch'
M, m, b = map(int, cur)
if re.fullmatch(r'\d+\.\d+\.\d+', a): new = a
elif a == 'major': new = f'{M+1}.0.0'
elif a == 'minor': new = f'{M}.{m+1}.0'
elif a == 'keep': new = f'{M}.{m}.{b}'
else: new = f'{M}.{m}.{b+1}'
open(p('js/version.js'), 'w').write(f"export const VERSION = '{new}';\n")
sw = open(p('sw.js')).read()
sw = re.sub(r"const VERSION = '[^']*';", f"const VERSION = '{new}';", sw, count=1)
open(p('sw.js'), 'w').write(sw)
import hashlib
imgs = {('img/q/' + f): hashlib.sha256(open(p('img/q', f), 'rb').read()).hexdigest()[:10] for f in sorted(os.listdir(p('img/q'))) if f.endswith('.webp')}
open(p('sw-assets.js'), 'w').write('// generated by tools/bump.py – image path → content hash (a changed image gets a new cache key)\nself.IMGS = ' + json.dumps(imgs) + ';\n')
print(new, len(imgs), 'images')
