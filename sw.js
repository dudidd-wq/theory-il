// Service worker: precache the app shell + Hebrew bank + question images; everything same-origin only.
importScripts('sw-assets.js'); // defines self.IMGS (list of image paths), generated by tools/bump.py
const VERSION = '1.0.1';
const PREFIX = 'theory-il-';
const SHELL = PREFIX + 'shell-' + VERSION;
const IMG = PREFIX + 'img-v1';            // image file names are stable (official question ids), kept across versions
const ASSETS = [
  './', 'index.html', 'manifest.webmanifest', 'css/style.css', 'fonts/rubik.woff2',
  'js/app.js', 'js/ui.js', 'js/store.js', 'js/backup.js', 'js/i18n.js', 'js/tts.js', 'js/version.js',
  'data/q.he.json', 'data/manifest.json',
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/maskable-512.png', 'icons/apple-touch-icon.png',
];
self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(SHELL);
    await c.addAll(ASSETS.map(u => new Request(u, { cache: 'reload' })));
    // images: best effort, so a flaky network doesn't block the shell; missing ones are fetched on demand later
    const ic = await caches.open(IMG); const have = new Set((await ic.keys()).map(r => new URL(r.url).pathname));
    const todo = (self.IMGS || []).filter(u => !have.has(new URL(u, self.registration.scope).pathname));
    for (let i = 0; i < todo.length; i += 20) await Promise.allSettled(todo.slice(i, i + 20).map(u => ic.add(u)));
  })());
});
self.addEventListener('message', e => { if (e.data === 'skip') self.skipWaiting(); });
self.addEventListener('activate', e => {
  // only touch this app's caches: the same github.io origin hosts other apps
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== SHELL && k !== IMG).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  if (/\/img\/q\/[\w.-]+\.webp$/.test(url.pathname)) {
    e.respondWith(caches.open(IMG).then(async c => (await c.match(req, { ignoreSearch: true })) ||
      fetch(req).then(r => { if (r.ok) c.put(req, r.clone()); return r; }).catch(() => new Response('', { status: 504 }))));
    return;
  }
  // data JSON: network-first so content fixes arrive, cache fallback offline (translations are cached when first used)
  if (/\/data\/[\w.]+\.json$/.test(url.pathname)) {
    e.respondWith(fetch(req).then(r => { if (r.ok) { const cl = r.clone(); caches.open(SHELL).then(c => c.put(req, cl)); } return r; })
      .catch(async () => (await caches.match(req, { ignoreSearch: true })) || new Response('{}', { status: 504 })));
    return;
  }
  // app shell: cache-first (new versions arrive with a new SW VERSION), network fallback
  e.respondWith((async () => {
    const hit = await caches.match(req, { ignoreSearch: true }) || (req.mode === 'navigate' ? await caches.match('index.html') : null);
    if (hit) return hit;
    try {
      const r = await fetch(req);
      if (r.ok && r.type === 'basic') { const cl = r.clone(); caches.open(SHELL).then(c => c.put(req, cl)); }
      return r;
    } catch { return req.mode === 'navigate' ? caches.match('index.html') : new Response('', { status: 504 }); }
  })());
});
