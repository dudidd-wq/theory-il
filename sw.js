// Service worker: precache the app shell + Hebrew bank + question images; everything same-origin only.
importScripts('sw-assets.js'); // defines self.IMGS ({path: content hash}), generated by tools/bump.py
const VERSION = '1.22.0';
const PREFIX = 'theory-il-';
const SHELL = PREFIX + 'shell-' + VERSION;
const IMG = PREFIX + 'img-v1';            // kept across versions; each entry is keyed path?h=<content hash>, so a corrected image refreshes
const IMGS = self.IMGS || {};
const imgKey = path => { const k = path.replace(/^.*?(img\/q\/)/, '$1'); return IMGS[k] ? new URL(k + '?h=' + IMGS[k], self.registration.scope).href : null; };
const ASSETS = [
  './', 'index.html', 'manifest.webmanifest', 'css/style.css', 'fonts/rubik.woff2',
  'js/app.js', 'js/ui.js', 'js/store.js', 'js/backup.js', 'js/i18n.js', 'js/tts.js', 'js/version.js', 'js/elig.js', 'js/learn.js', 'js/steps.js', 'js/viz.js', 'img/hero.svg',
  'data/q.he.json', 'data/manifest.json', 'data/lessons.json', 'data/sources.json', 'data/coverage.json', 'data/signs.json',
  'icons/icon-192.png', 'icons/icon-512.png', 'icons/maskable-512.png', 'icons/apple-touch-icon.png',
];
self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(SHELL);
    await c.addAll(ASSETS.map(u => new Request(u, { cache: 'reload' })));
    // images: best effort, so a flaky network doesn't block the shell; missing ones are fetched on demand later
    const ic = await caches.open(IMG); const have = new Set((await ic.keys()).map(r => r.url));
    const todo = Object.keys(IMGS).map(imgKey).filter(k => !have.has(k));
    const batch = async list => { const bad = []; for (let i = 0; i < list.length; i += 20) { const part = list.slice(i, i + 20);
      (await Promise.allSettled(part.map(k => ic.add(new Request(k, { cache: 'reload' }))))).forEach((r, j) => { if (r.status !== 'fulfilled') bad.push(part[j]); }); } return bad; };
    let bad = await batch(todo);
    if (bad.length) bad = await batch(bad);          // one retry for images that failed (flaky network)
    if (todo.length) {                               // tell open pages the true count ("X of N saved")
      const n = Object.keys(IMGS).length, ok = n - bad.length;
      for (const c of await self.clients.matchAll({ includeUncontrolled: true })) c.postMessage({ type: 'imgs', ok, n });
    }
  })());
});
self.addEventListener('message', e => { if (e.data === 'skip') self.skipWaiting(); });
self.addEventListener('activate', e => {
  // only touch this app's caches: the same github.io origin hosts other apps
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== SHELL && k !== IMG).map(k => caches.delete(k))))
    .then(async () => { const ic = await caches.open(IMG); for (const r of await ic.keys()) if (r.url !== imgKey(new URL(r.url).pathname)) await ic.delete(r); })   // drop stale image versions
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  if (/\/img\/q\/[\w.-]+\.webp$/.test(url.pathname)) {
    const key = imgKey(url.pathname);
    e.respondWith(caches.open(IMG).then(async c => (key && await c.match(key)) ||
      fetch(key || req).then(r => { if (r.ok && key) c.put(key, r.clone()); return r; }).catch(() => new Response('', { status: 504 }))));
    return;
  }
  // data JSON: network-first so content fixes arrive, cache fallback offline (translations are cached when first used)
  if (/\/data\/[\w.]+\.json$/.test(url.pathname)) {
    // with a cached copy, a slow network ("lie-fi") falls back to it after 4 s instead of hanging
    const net = fetch(req).then(r => { if (r.ok) { const cl = r.clone(); caches.open(SHELL).then(c => c.put(req, cl)); } return r; });
    e.respondWith((async () => {
      const cached = await caches.match(req, { ignoreSearch: true });
      if (!cached) return net.catch(() => new Response('{}', { status: 504 }));
      return Promise.race([net.then(r => r.ok ? r : cached, () => cached), new Promise(r => setTimeout(() => r(cached), 4000))]);
    })());
    return;
  }
  // app shell: cache-first (new versions arrive with a new SW VERSION), network fallback
  e.respondWith((async () => {
    const hit = await caches.match(req, { ignoreSearch: true }) || (req.mode === 'navigate' ? await caches.match('index.html') : null);
    if (hit) return hit;
    try {
      const r = await fetch(req);
      if (r.ok && r.type === 'basic') { const cl = r.clone(); caches.open(SHELL).then(c => c.put(req, cl)); }
      return r;
    } catch { return req.mode === 'navigate' ? caches.match('index.html') : new Response('', { status: 504 }); }
  })());
});
